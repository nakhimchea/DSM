"""Data cards: what went into a dataset, under which licence, and what was removed."""

from __future__ import annotations

import datetime as dt
import json
from collections import Counter
from pathlib import Path


def write_card(
    out_dir: str | Path, *, name: str, sources: list[dict], stats: dict[str, Counter | dict], notes: str = ""
) -> Path:
    """``DATACARD.md`` + ``datacard.json``. ``sources``: catalogue entries; ``stats``: stage -> counter."""
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    payload = {
        "name": name,
        "created": dt.datetime.now(dt.timezone.utc).isoformat(timespec="seconds"),
        "sources": sources,
        "stats": {stage: dict(counter) for stage, counter in stats.items()},
        "notes": notes,
    }
    (out / "datacard.json").write_text(
        json.dumps(payload, indent=2, ensure_ascii=False, default=str) + "\n", encoding="utf-8"
    )
    lines = [f"# Data card: {name}", "", f"Created {payload['created']}.", ""]
    lines += [
        "## Sources",
        "",
        "| Source | Kind | Languages | Licence | Tier | Generated by |",
        "|---|---|---|---|---|---|",
    ]
    for s in sources:
        lines.append(
            f"| {s.get('name')} | {s.get('kind')} | {', '.join(s.get('langs', []))} | {s.get('license')} | {s.get('tier')} | {s.get('generated_by')} |"
        )
    for stage, counter in payload["stats"].items():
        lines += ["", f"## {stage}", "", "| Counter | Value |", "|---|---:|"]
        lines += [
            f"| {key} | {value:,} |" if isinstance(value, int) else f"| {key} | {value} |"
            for key, value in sorted(counter.items())
        ]
    if any(s.get("internal") for s in sources):
        lines += ["", "**INTERNAL DATA**: models trained on this dataset must not be published."]
    if notes:
        lines += ["", "## Notes", "", notes]
    (out / "DATACARD.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    return out / "DATACARD.md"
